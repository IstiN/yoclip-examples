// Акцент фона по сценам (холодный синий -> фиолетовый -> багровый).
var ACCENTS = [C.ice, C.blue, C.violet, C.ice, C.ice, C.red, C.redDeep,
  C.violet, C.red, C.ice, C.red, C.red];
var SCENE_STARTS = [STARTS.phone, STARTS.puddle, STARTS.mic, STARTS.screentime, STARTS.phones,
  STARTS.silhouette, STARTS.shadow, STARTS.chorus, STARTS.glass, STARTS.chat,
  STARTS.heart, STARTS.ember];

function sceneAccent(f) {
  var idx = 0;
  for (var i = 0; i < SCENE_STARTS.length; i++) if (f >= SCENE_STARTS[i]) idx = i;
  return ACCENTS[idx];
}
